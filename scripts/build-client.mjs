/**
 * Build the browser half of the plugin.
 *
 * The UI is the vendored chat-demo application (`vendor/chat-demo/src`), so the
 * build has two passes: the first bundles the app to collect its CSS, the
 * second rebundles the entry with that CSS inlined as a string. The factory the
 * module loader receives stays side-effect free: the stylesheet is appended in
 * `apply`, and React comes from the host module table rather than the bundle.
 */
import { build } from 'esbuild'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const tmp = path.join(root, 'build', 'tmp')

const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
if (!pkg.dsh || !pkg.dsh.client) throw new Error('package.json is missing dsh.client')
const bundleId = pkg.name

/** Modules the host module table already provides. */
const EXTERNAL = ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', 'react/jsx-dev-runtime']

const common = {
  entryPoints: [path.join(root, 'src', 'entry.tsx')],
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: ['chrome120'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  inject: [path.join(root, 'src', 'react-shim.ts')],
  external: EXTERNAL,
  loader: {
    '.css': 'css',
    '.svg': 'dataurl',
    '.png': 'dataurl',
    '.woff2': 'dataurl',
    // Only woff2 is inlined; the woff/ttf fallbacks would triple the bundle for nothing.
    '.woff': 'empty',
    '.ttf': 'empty',
    '.eot': 'empty',
  },
  define: {
    'process.env.NODE_ENV': '"production"',
    // The panel shows its own version and compares it with the published index.
    __PLUGIN_VERSION__: JSON.stringify(pkg.version),
    // The demo injects its API origin at build time; keep the public default.
    __API_ORIGIN__: JSON.stringify(process.env.DSH_CHAT_API_ORIGIN || 'https://api.deepseek.com'),
  },
  logLevel: 'warning',
  legalComments: 'none',
}

/**
 * Keep the demo stylesheet inside the panel: its tokens and resets are written
 * for a whole document, so `:root`, `html` and `body` become the panel host.
 */
function scopeCss(css) {
  const HOST = '.dsc-demo-host'
  // Doubling the class beats the host's html-level token rules (0,1,1), so the
  // panel keeps the demo palette without touching the rest of the page.
  const ROOT = `${HOST}${HOST}`
  return css
    .replace(/(^|[\s,{}])html(\s*[{,])/g, `$1${ROOT}$2`)
    .replace(/(^|[\s,{}])body(\s*[{,.])/g, `$1${ROOT}$2`)
    .replace(/(^|[\s,{}]):root(\s*[{,])/g, `$1${ROOT}$2`)
    .replace(/body\.dark/g, `${ROOT}.dark`)
    .replace(/body\.light/g, `${ROOT}.light`)
    .replace(/body\[data-ds-dark-theme\]/g, `${ROOT}[data-ds-dark-theme]`)
    .replace(/body\.change-theme/g, `${ROOT}.change-theme`)
}

const entryBundle = path.join(tmp, 'entry.js')

await rm(tmp, { recursive: true, force: true })
await mkdir(tmp, { recursive: true })
await mkdir(path.join(root, 'src', 'generated'), { recursive: true })
// Pass 1 needs the module the entry imports, so seed an empty stylesheet first.
await writeFile(
  path.join(root, 'src', 'generated', 'css.ts'),
  'export const CSS_TEXT = ""\n',
  'utf8',
)

// Pass 1: bundle to collect the CSS the application imports.
await build({ ...common, outfile: entryBundle, write: true })
const cssPath = entryBundle.replace(/\.js$/, '.css')
const rawCss = await readFile(cssPath, 'utf8').catch(() => '')
if (!rawCss) throw new Error('the application imported no CSS; the build would render unstyled')
const scopedCss = scopeCss(rawCss)

await mkdir(path.join(root, 'src', 'generated'), { recursive: true })
await writeFile(
  path.join(root, 'src', 'generated', 'css.ts'),
  `// Generated by scripts/build-client.mjs — do not edit.\nexport const CSS_TEXT = ${JSON.stringify(scopedCss)}\n`,
  'utf8',
)

// Pass 2: bundle again with the stylesheet inlined, then wrap it in the loader.
const outfile = path.join(tmp, 'bundle.js')
await build({ ...common, outfile, write: true })
const bundleJs = await readFile(outfile, 'utf8')

const wrapper = `/* Built by scripts/build-client.mjs from vendor/chat-demo — do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(bundleId)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${bundleJs.replace(/^/gm, '    ')}
    return module.exports && module.exports.default ? module.exports.default : module.exports;
  },
});
`

await writeFile(path.join(root, 'client.js'), wrapper, 'utf8')

const cssKb = (Buffer.byteLength(scopedCss) / 1024).toFixed(0)
const jsKb = (Buffer.byteLength(wrapper) / 1024).toFixed(0)
console.log(`client.js ${jsKb} KB · inlined CSS ${cssKb} KB · bundle id ${bundleId}`)
